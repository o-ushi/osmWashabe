  static const _themePool = [
    '料理・食事・グルメ',
    'スポーツ・運動・健康管理',
    '旅行・観光・お出かけ',
    'AI・最先端テクノロジー・生成AI活用',
    'SNS・スマートフォン・デジタルライフ',
    '家族・子育て・親との関係',
    '趣味・コレクション・こだわりの世界',
    '環境・自然・季節の変わり目',
    '映画・ドラマ・アニメ・エンタメ',
    '音楽・コンサート・好きなアーティスト',
    'ファッション・買い物・インテリア',
    '時事ニュース・政治・経済・社会問題',
    '住まい・生活習慣・片付け',
    '学校・資格・キャリアアップ',
    '友人・コミュニティ・趣味のサークル',
    'ペット・動物・植物',
    'お金・節約・投資',
    '将来の夢・人生の目標',
    'ボランティア・地域活動・社会貢献',
    '健康・医療・ウェルネス',
    '子どものころの思い出・懐かしい体験',
    '多様性・異文化・海外生活',
    '芸術・美術・写真・創作活動',
    '有名人・スポーツ選手・著名人への印象や学び',
    'ゲーム・eスポーツ・VR体験',
    '読書・本・好きな作家',
    'サイエンス・宇宙・最新研究',
    '自分の性格・強み・失敗から学んだこと',
  ];

  // ランダムなテーマヒントを埋め込んだプロンプトを生成する
  static String get batchPrompt {
    final rng = Random();
    final pool = [..._themePool]..shuffle(rng);
    final hints = pool.take(5).join('、');

    return '''
あなたは日本語スピーチ練習用のお題を作成するアシスタントです。
以下3分野のお題を、それぞれ10問ずつ作成してください。

【今回のテーマ（必ず反映すること）】
$hints
※ 上記テーマを積極的に取り入れ、各分野で偏りなく使ってください。

【出力形式（この見出しを必ず使う）】

【日常の身近な話題】（45秒スピーチ・10問）
1. （質問文）
2. （質問文）
…（10問）

【ビジネスシーン】（45秒スピーチ・10問）
1. （質問文）
…（10問）

【シチュエーション】（15秒準備＋60秒発話・10問）
1. 状況：（状況の文章）／条件：（守るべき条件）
…（10問）

【ルール】
- 見出し行は必ず【日常の身近な話題】【ビジネスシーン】【シチュエーション】を付ける
- 1行に1問だけ書く
- 質問文・状況文だけを書き、解説や挨拶は不要
- 日本語で、自然で話しやすい表現にする
- 【日常の身近な話題】は私生活・趣味・経験・時事ニュース・テクノロジー・芸術・有名人・スポーツ選手など幅広い話題を扱う
- 【ビジネスシーン】は職場・取引・上司同僚・クライアントなどの場面を想定する
- テーマを積極的に活かし、毎回異なる切り口のバラエティに富んだお題を作ること
''';
  }
}
